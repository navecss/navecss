/**
 * The form of the five files of an item, read against the package's own source for its subpath: the
 * entry is the package's `index.ts` less its directive and lint comment, the parts file is the
 * package's generated module with the helper and the classes redirected, and the wrap file is
 * `src/part.ts`. Each check is a pure function over a registry item.
 */
import ts from 'typescript'

import type { Problem } from './files-problem.ts'
import type { RegistryItem } from './load.ts'

import { cleared } from './cleared.ts'
import { headerFor, type Notice } from './files-header.ts'
import { foldWhitespace, localNameByClass, type PackageSources } from './files-sources.ts'
import { typesComment, typesRules } from './files-types-comment.ts'

export const TARGET_DIR = 'components/nave/'

/**
 * The targets of an item, in R3's order.
 */
export const targetsFor = (subpath: string): string[] =>
  [
    `nave-${subpath}.ts`,
    `nave-${subpath}.parts.ts`,
    `nave-${subpath}.wrap.ts`,
    `nave-${subpath}.module.css`,
    'NAVECSS-LICENSE',
  ].map((name) => `${TARGET_DIR}${name}`)

const squashBlankLines = (text: string): string => text.replaceAll(/\n\s*\n/g, '\n').trim()

const DIRECTIVE_LINE = /^'use client'\n/m
const LINT_COMMENT_LINE = /^\/\* eslint-disable [^\n]*\*\/\n/m
const GENERATED_BY_LINE = /^\/\/ Generated by [^\n]*\n/m

const withoutHeader = (content: string, header: string): string =>
  content.startsWith(header) ? content.slice(header.length) : content

const firstDifference = (actual: string, expected: string): string => {
  let at = 0
  while (at < actual.length && actual[at] === expected[at]) at += 1
  return `at character ${at}: ${JSON.stringify(actual.slice(at, at + 70))} against ${JSON.stringify(expected.slice(at, at + 70))}`
}

const contentOf = (item: RegistryItem, target: string): string | undefined =>
  item.files.find((file) => file.target === target)?.content

/**
 * The entry: the header, then the package's `index.ts` less its directive line and its lint
 * comment, `./parts.generated.ts` read as `./nave-<s>.parts`. Blank lines between statements are
 * the generator's to lay out, so they are folded before the comparison.
 */
const entryProblems = (
  item: RegistryItem,
  subpath: string,
  notice: Notice,
  sources: PackageSources,
): Problem[] => {
  const target = `${TARGET_DIR}nave-${subpath}.ts`
  const content = contentOf(item, target)
  if (content === undefined) return []
  const at = { file: target, item: item.name }
  const problems: Problem[] = []
  const header = headerFor('ts', notice)
  const body = withoutHeader(content, header)
  if (/^\s*['"]use client['"]/m.test(body)) {
    problems.push({ ...at, message: "the entry has a 'use client' directive" })
  }
  if (content.includes('eslint-disable')) {
    problems.push({
      ...at,
      message: 'the entry carries the package index lint comment (eslint-disable)',
    })
  }
  const expected = sources.index
    .replace(DIRECTIVE_LINE, '')
    .replace(LINT_COMMENT_LINE, '')
    .replace('./parts.generated.ts', () => `./nave-${subpath}.parts`)
  if (squashBlankLines(body) !== squashBlankLines(expected)) {
    problems.push({
      ...at,
      message: `the entry is not the package index less its directive and lint comment, ${firstDifference(squashBlankLines(body), squashBlankLines(expected))}`,
    })
  }
  return problems
}

const wrapProblems = (
  item: RegistryItem,
  subpath: string,
  notice: Notice,
  sources: PackageSources,
): Problem[] => {
  const target = `${TARGET_DIR}nave-${subpath}.wrap.ts`
  const content = contentOf(item, target)
  if (content === undefined) return []
  return content === `${headerFor('ts', notice)}${sources.part}`
    ? []
    : [{ file: target, item: item.name, message: 'is not the header followed by src/part.ts' }]
}

const CLASS_LITERAL = /'(nave-base-ui-[\w-]+(?: nave-base-ui-[\w-]+)*)'/g
const STYLES_EXPRESSION = /`\$\{styles\.\w+\}(?: \$\{styles\.\w+\})*`|\bstyles\.\w+/g

/**
 * A class string, as the local names of its atoms in order, between marks. The package spells it as
 * a literal of `nave-base-ui-` classes; a copy spells it from `styles.<local name>` only.
 */
const markedClasses = (names: readonly string[]): string => `§${names.join(' ')}§`

const packageOutline = (subpath: string, sources: PackageSources): string => {
  const localNames = localNameByClass()
  const classes = sources.generated
    .replace(DIRECTIVE_LINE, '')
    .replace(GENERATED_BY_LINE, '')
    .replace("'../part.ts'", () => `'./nave-${subpath}.wrap'`)
    .replaceAll(CLASS_LITERAL, (_match, literal: string) =>
      markedClasses(literal.split(' ').map((name) => localNames.get(name) ?? `?${name}`)),
    )
  return foldWhitespace(classes).replaceAll(
    /(export const \w+): (PartOf<typeof Base, '(\w+)'>) = \/\*#__PURE__\*\/ \(\(\) => Base\.\3\)\(\)/g,
    "$1: $2 = /*#__PURE__*/ (() => (Base as Record<string, unknown>).$3 as PartOf<typeof Base, '$3'>)()",
  )
}

const copyOutline = (body: string, subpath: string): { missingImport: boolean; text: string } => {
  const importLine = new RegExp(
    String.raw`^import styles from '\./nave-${subpath}\.module\.css'\n`,
    'm',
  )
  const withoutImport = body.replace(importLine, '')
  const text = withoutImport
    .replace(/^\s*'use client'\n/, '')
    .replace(/^\/\* eslint-disable [^\n]*\*\/\n/, '')
    .replaceAll(STYLES_EXPRESSION, (expression) =>
      markedClasses(
        expression
          .matchAll(/styles\.(\w+)/g)
          .map((match) => match[1] ?? '')
          .toArray(),
      ),
    )
  return { missingImport: withoutImport === body, text: foldWhitespace(text) }
}

const importedSpecifiers = (content: string): string[] =>
  // eslint-disable-next-line import-x/no-named-as-default-member -- TypeScript is CommonJS, and its default export is the one form Node's ESM loader gives every member of
  ts.preProcessFile(content, true, true).importedFiles.map((imported) => imported.fileName)

const allowedImports = (subpath: string, sources: PackageSources): Set<string> =>
  new Set([
    'react',
    ...importedSpecifiers(sources.generated).filter((name) => name.startsWith('@base-ui/react/')),
    `./nave-${subpath}.module.css`,
    `./nave-${subpath}.wrap`,
  ])

/**
 * The lint comment sits alone on the line after `'use client'`, names exactly the rules the file
 * needs, and is the only `eslint-disable` in the file.
 */
const typesCommentProblems = (
  body: string,
  at: Omit<Problem, 'message'>,
  sources: PackageSources,
): Problem[] => {
  const expected = typesComment(typesRules(sources.generated))
  const problems: Problem[] = []
  if (!body.startsWith(`'use client'\n${expected}\n`)) {
    problems.push({
      ...at,
      message: `the line after 'use client' is not exactly ${expected}`,
    })
  }
  const count = body.split('eslint-disable').length - 1
  if (count !== 1) {
    problems.push({ ...at, message: `has ${count} eslint-disable comments, not one` })
  }
  return problems
}

const partsProblems = (
  item: RegistryItem,
  subpath: string,
  notice: Notice,
  sources: PackageSources,
): Problem[] => {
  const target = `${TARGET_DIR}nave-${subpath}.parts.ts`
  const content = contentOf(item, target)
  if (content === undefined) return []
  const at = { file: target, item: item.name }
  const problems: Problem[] = []
  const body = withoutHeader(content, headerFor('ts', notice))
  if (!body.startsWith("'use client'")) {
    problems.push({ ...at, message: "'use client' is not the first statement after the header" })
  }
  problems.push(...typesCommentProblems(body, at, sources))
  if (content.includes('nave-base-ui-')) {
    problems.push({ ...at, message: 'a class is still spelt as a nave-base-ui- string' })
  }
  const copy = copyOutline(body, subpath)
  if (copy.missingImport) {
    problems.push({ ...at, message: `does not import styles from ./nave-${subpath}.module.css` })
  }
  const expected = packageOutline(subpath, sources)
  if (copy.text !== expected) {
    problems.push({
      ...at,
      message: `differs from the package module once the helper, the classes and the Generated by line are redirected, ${firstDifference(copy.text, expected)}`,
    })
  }
  const allowed = allowedImports(subpath, sources)
  const foreign = importedSpecifiers(content).filter((name) => !allowed.has(name))
  for (const specifier of foreign) {
    problems.push({ ...at, message: `imports ${specifier}, which the package module does not` })
  }
  return problems
}

const targetProblems = (item: RegistryItem, subpath: string): Problem[] => {
  const actual = item.files.map((file) => file.target)
  const expected = targetsFor(subpath)
  return actual.join('\n') === expected.join('\n')
    ? []
    : [
        {
          file: '(targets)',
          item: item.name,
          message: `targets are ${JSON.stringify(actual)}, not ${JSON.stringify(expected)}`,
        },
      ]
}

const COMMENT_FORMS: readonly RegExp[] = [/eslint-disable/, /@ts-/, /stylelint-disable/]

/**
 * No file carries a lint or type-check suppression, other than the one cleared outline comment.
 */
const suppressionProblems = (
  item: RegistryItem,
  subpath: string,
  sources: PackageSources,
): Problem[] => {
  const outline = cleared('W-outline')
  const types = typesComment(typesRules(sources.generated))
  return item.files.flatMap((file) => {
    const allowed = file.target.endsWith(`nave-${subpath}.parts.ts`) ? [outline, types] : [outline]
    const rest = allowed.reduce((text, comment) => text.replaceAll(comment, ''), file.content ?? '')
    return COMMENT_FORMS.filter((form) => form.test(rest)).map((form) => ({
      file: file.target,
      item: item.name,
      message: `carries a ${form.source} comment other than the cleared outline and types comments`,
    }))
  })
}

/**
 * Everything AC-10 asks of one item.
 */
export const itemFormProblems = (
  item: RegistryItem,
  subpath: string,
  notice: Notice,
  sources: PackageSources,
): Problem[] => [
  ...targetProblems(item, subpath),
  ...entryProblems(item, subpath, notice, sources),
  ...partsProblems(item, subpath, notice, sources),
  ...wrapProblems(item, subpath, notice, sources),
  ...suppressionProblems(item, subpath, sources),
]
