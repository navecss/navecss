import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

import {
  declarationsOfClass,
  exportStatement,
  snapshotOf,
} from './support/registry/files-generated.ts'
import {
  makePackageCopy,
  type PackageCopy,
  readInCopy,
  replaceOnceInCopy,
  type RunResult,
  runScript,
  runScriptLine,
} from './support/registry/files-package-copy.ts'
import { fileOf, type LoadedRegistry, loadRegistry } from './support/registry/load.ts'
import { componentSubpaths } from './support/registry/styled-subpaths.ts'
import { PACKAGE_DIR } from './support/stylesheet.ts'

// A build in a copy runs the package's own scripts, and the wrapper generator reads two Base UI
// versions' declarations; both take a minute or more on a busy machine.
const BUILD_MS = 900_000
const REPOSITORY_DIR = path.resolve(PACKAGE_DIR, '../..')

interface Manifest {
  dependencies?: Record<string, string>
  devDependencies?: Record<string, string>
  peerDependencies?: Record<string, string>
  scripts: Record<string, string>
}

const manifest = (): Manifest =>
  JSON.parse(readFileSync(path.join(PACKAGE_DIR, 'package.json'), 'utf8')) as Manifest

const git = (...args: string[]): string =>
  execFileSync('git', ['-C', REPOSITORY_DIR, ...args], { encoding: 'utf8' })

const packageModule = (subpath: string): string =>
  readFileSync(path.join(PACKAGE_DIR, 'src', subpath, 'parts.generated.ts'), 'utf8')

const EXACT_VERSION = /^\d+\.\d+\.\d+(?:-[\w.]+)?$/

/**
 * The commands of a package script chained with `&&`, in order.
 */
const commandsOf = (script: string): string[] => script.split('&&').map((part) => part.trim())

describe('AC-base-ui-registry-16: The registry is generated by the build from the package source, kept fresh, never committed', () => {
  describe('the wiring, read from the package, turbo.json and .gitignore', () => {
    it('has scripts/generate-registry.ts, and build runs it after build-styles.ts', () => {
      expect(existsSync(path.join(PACKAGE_DIR, 'scripts/generate-registry.ts'))).toBe(true)
      const commands = commandsOf(manifest().scripts.build ?? '')
      const styles = commands.findIndex((command) => command.includes('scripts/build-styles.ts'))
      const registry = commands.findIndex((command) =>
        command.includes('scripts/generate-registry.ts'),
      )
      expect(styles).toBeGreaterThanOrEqual(0)
      expect(registry).toBeGreaterThan(styles)
    })

    it('has @navecss/core a devDependency only, and prettier and shadcn exact devDependencies', () => {
      const { dependencies, devDependencies, peerDependencies } = manifest()
      expect(devDependencies?.['@navecss/core']).toBeDefined()
      expect(Object.keys(dependencies ?? {})).not.toContain('@navecss/core')
      expect(Object.keys(peerDependencies ?? {})).not.toContain('@navecss/core')
      for (const name of ['prettier', 'shadcn']) {
        expect(devDependencies?.[name], name).toMatch(EXACT_VERSION)
      }
    })

    it('commits nothing under packages/base-ui/dist, and ignores the registry directory', () => {
      expect(git('ls-files', 'packages/base-ui/src').length).toBeGreaterThan(0)
      expect(git('ls-files', 'packages/base-ui/dist')).toBe('')
      expect(() => {
        git('check-ignore', '--quiet', 'packages/base-ui/dist/registry/registry.json')
      }).not.toThrow()
    })

    it('has turbo cache and restore dist/registry, and clean remove it', () => {
      const turbo = JSON.parse(readFileSync(path.join(REPOSITORY_DIR, 'turbo.json'), 'utf8')) as {
        tasks: Record<string, { outputs?: string[] }>
      }
      const build = turbo.tasks['@navecss/base-ui#build'] ?? turbo.tasks.build
      const outputs = build?.outputs ?? []
      expect(outputs.length).toBeGreaterThan(0)
      expect(outputs.some((glob) => path.matchesGlob('dist/registry/registry.json', glob))).toBe(
        true,
      )
      expect(
        outputs.some((glob) => path.matchesGlob('dist/registry/base-ui-dialog.json', glob)),
      ).toBe(true)
      expect(commandsOf(manifest().scripts.clean ?? '')).toEqual(['rm -rf dist'])
    })
  })

  describe('the build, run twice in a copy without clean', () => {
    let copy: PackageCopy
    let first: Map<string, string>
    let second: Map<string, string>
    const runs: RunResult[] = []

    beforeAll(() => {
      copy = makePackageCopy()
      const build = readInCopy(copy, 'package.json')
      const line = (JSON.parse(build) as Manifest).scripts.build ?? ''
      const registry = path.join(copy.packageDir, 'dist/registry')
      runs.push(runScriptLine(copy, line))
      first = snapshotOf(registry)
      mkdirSync(registry, { recursive: true })
      writeFileSync(path.join(registry, 'base-ui-zzz.json'), '{}\n')
      runs.push(runScriptLine(copy, line))
      second = snapshotOf(registry)
    }, BUILD_MS)
    afterAll(() => {
      copy.cleanup()
    })

    it('succeeds both times, with the package build script as it is', () => {
      expect(
        runs.map((run) => run.status),
        runs.map((run) => run.output.slice(-1500)).join('\n'),
      ).toEqual([0, 0])
    })

    it('drops a planted item, because the generator empties the directory first', () => {
      expect(first.has('base-ui-dialog.json')).toBe(true)
      expect(second.has('base-ui-zzz.json')).toBe(false)
      expect(second.get('registry.json')).not.toContain('base-ui-zzz')
    })

    it('writes the same registry the second time, byte for byte, as a cache hit restores it', () => {
      expect(second.size).toBeGreaterThan(0)
      expect(second).toEqual(first)
    })
  })

  describe('the roster mutation: Dialog.Popup takes another atom, with no other edit', () => {
    const NEW_ATOM = 'baseUiPopoverPopup'
    const NEW_CLASS = 'nave-base-ui-popover-popup'
    const NEW_LOCAL = 'popoverPopup'
    const OLD_CLASS = 'nave-base-ui-dialog-popup'
    const OLD_LOCAL = 'dialogPopup'
    let copy: PackageCopy
    let steps: RunResult[]

    beforeAll(() => {
      copy = makePackageCopy()
      replaceOnceInCopy(
        copy,
        'scripts/wrappers/roster.ts',
        "'Dialog.Popup': atoms('baseUiDialogPopup', 'baseUiPopupFade'),",
        `'Dialog.Popup': atoms('${NEW_ATOM}', 'baseUiPopupFade'),`,
      )
      steps = [
        runScript(copy, 'build-styles.ts'),
        runScript(copy, 'generate-wrappers.ts'),
        runScript(copy, 'generate-registry.ts', ['--root', copy.packageDir]),
      ]
    }, BUILD_MS)
    const registryOfCopy = (): LoadedRegistry =>
      loadRegistry(path.join(copy.packageDir, 'dist/registry'))
    afterAll(() => {
      copy.cleanup()
    })

    it('runs the three build steps', () => {
      expect(
        steps.map((step) => step.status),
        steps.map((step) => step.output.slice(-1500)).join('\n'),
      ).toEqual([0, 0, 0])
    })

    it('regenerates every other wrapper module of the copy exactly as the package has it', () => {
      const others = componentSubpaths().filter((subpath) => subpath !== 'dialog')
      expect(others.length).toBeGreaterThan(0)
      for (const subpath of others) {
        const generated = `src/${subpath}/parts.generated.ts`
        expect(readInCopy(copy, generated), subpath).toBe(packageModule(subpath))
      }
      expect(readInCopy(copy, 'src/dialog/parts.generated.ts')).not.toBe(packageModule('dialog'))
    })

    it("moves the package's Dialog.Popup class to the new atom", () => {
      const popup = exportStatement(readInCopy(copy, 'src/dialog/parts.generated.ts'), 'Popup')
      expect(popup).toContain(`'${NEW_CLASS} nave-base-ui-popup-fade'`)
      expect(popup).not.toContain(OLD_CLASS)
    })

    it("moves the copy's styles reference to the new atom, and leaves the other items alone", () => {
      const registry = registryOfCopy()
      const dialog = registry.items.get('base-ui-dialog')
      if (dialog === undefined) throw new Error('the registry has no base-ui-dialog')
      const popup = exportStatement(fileOf(dialog, 'nave-dialog.parts.ts'), 'Popup')
      expect(popup).toContain(`styles.${NEW_LOCAL}`)
      expect(popup).toContain('styles.popupFade')
      expect(popup).not.toContain(`styles.${OLD_LOCAL}`)
      const alert = registry.items.get('base-ui-alert-dialog')
      if (alert === undefined) throw new Error('the registry has no base-ui-alert-dialog')
      expect(exportStatement(fileOf(alert, 'nave-alert-dialog.parts.ts'), 'Popup')).toContain(
        `styles.${OLD_LOCAL}`,
      )
    })

    it("carries the new atom's rules in the copy's module, and no longer the old atom's", () => {
      const dialog = registryOfCopy().items.get('base-ui-dialog')
      if (dialog === undefined) throw new Error('the registry has no base-ui-dialog')
      const module = fileOf(dialog, 'nave-dialog.module.css')
      const stylesheet = readInCopy(copy, 'dist/styles.css')
      const expected = declarationsOfClass(stylesheet, NEW_CLASS)
      expect(expected.length).toBeGreaterThan(0)
      const renamed = expected.map((line) =>
        line.replaceAll(`.${NEW_CLASS}`, () => `.${NEW_LOCAL}`),
      )
      expect(declarationsOfClass(module, NEW_LOCAL)).toEqual(renamed)
      expect(declarationsOfClass(module, OLD_LOCAL)).toEqual([])
    })
  })
})
