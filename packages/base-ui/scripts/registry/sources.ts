/**
 * The TypeScript files of an item, derived from the package's own generated modules: the entry
 * (the package's `index.ts` for the subpath), the parts module (its `parts.generated.ts` with each
 * class read from the item's CSS Module) and the wrap file (`src/part.ts`, unchanged).
 */
import { RegistryBuildError } from './errors.ts'
import { localName } from './module-css.ts'

const CLASS_LITERAL = /'(nave-base-ui-[a-z0-9 -]+)'/g

const itemStem = (subpath: string): string => `nave-${subpath}`

const mustReplace = (text: string, pattern: RegExp | string, to: string, what: string): string => {
  const result = text.replace(pattern, () => to)
  if (result === text) throw new RegistryBuildError(`the package's source no longer has ${what}`)
  return result
}

/**
 * `'nave-base-ui-dialog-popup nave-base-ui-popup-fade'` as the CSS Module's expression, and the
 * atoms it names.
 */
const classExpression = (
  classes: string,
  atomOfClass: ReadonlyMap<string, string>,
  used: Set<string>,
): string => {
  const references = classes.split(' ').map((className) => {
    const atom = atomOfClass.get(className)
    if (atom === undefined) throw new RegistryBuildError(`no atom is the class ${className}`)
    used.add(atom)
    return `styles.${localName(atom)}`
  })
  const [only] = references
  return only !== undefined && references.length === 1
    ? only
    : `\`${references.map((reference) => `\${${reference}}`).join(' ')}\``
}

/**
 * A part younger than the Base UI floor is read through a cast: a direct property access fails the
 * floor's types, and a copy is source a consumer's `skipLibCheck` does not skip.
 */
const castYoungParts = (text: string): string =>
  text.replaceAll(
    /(PartOf<typeof Base, '(\w+)'> = \/\*#__PURE__\*\/ \(\(\) => )Base\.\2(\)\(\))/g,
    "$1(Base as Record<string, unknown>).$2 as PartOf<typeof Base, '$2'>$3",
  )

const NAMESPACE_RULE = '@typescript-eslint/no-namespace'
const ANY_RULE = '@typescript-eslint/no-explicit-any'

const TYPES_REASON =
  'the types keep the names and generic defaults @navecss/base-ui exports, so code typed against the package compiles here unchanged'

/**
 * The one file-level lint comment of a parts file, naming exactly the `typescript-eslint` rules the
 * file's code trips under that config's `recommended`: the type namespaces that carry
 * `<Part>.Props` and `.State` in every file, and an explicit `any` only where the package's module
 * has one (a generic default). A directive that suppresses nothing is itself reported.
 */
export const typesComment = (rules: readonly string[]): string =>
  `/* eslint-disable ${rules.join(', ')} -- ${TYPES_REASON} */`

const typesRulesFor = (generated: string): string[] =>
  /\bany\b/.test(generated) ? [NAMESPACE_RULE, ANY_RULE] : [NAMESPACE_RULE]

export interface PartsModule {
  readonly text: string
  /**
  The atoms the parts use.
   */
  readonly used: ReadonlySet<string>
}

export const partsModule = (
  subpath: string,
  generated: string,
  atomOfClass: ReadonlyMap<string, string>,
  header: string,
): PartsModule => {
  const used = new Set<string>()
  let text = mustReplace(
    generated,
    /^'use client'\n\/\/ Generated by[^\n]*\n/,
    '',
    'the generated-by line',
  )
  text = mustReplace(text, "from '../part.ts'", `from './${itemStem(subpath)}.wrap'`, 'part.ts')
  text = text.replaceAll(CLASS_LITERAL, (_match, classes: string) =>
    classExpression(classes, atomOfClass, used),
  )
  text = castYoungParts(text)
  text = mustReplace(
    text,
    /^(import \{ \w+ as Base \} from '@base-ui\/react\/[a-z-]+'\n)/m,
    `$1import styles from './${itemStem(subpath)}.module.css'\n`,
    "Base UI's import",
  )
  const comment = typesComment(typesRulesFor(generated))
  return { text: `${header}'use client'\n${comment}\n${text}`, used }
}

export const entryModule = (subpath: string, packageIndex: string, header: string): string => {
  let text = mustReplace(packageIndex, "'use client'\n", '', "the entry's directive")
  text = text.replace(/^\/\* eslint-disable[^\n]*\n/m, '')
  text = mustReplace(
    text,
    "'./parts.generated.ts'",
    `'./${itemStem(subpath)}.parts'`,
    'the parts import',
  )
  return `${header}${text}`
}

export const wrapModule = (part: string, header: string): string => `${header}${part}`
