#!/usr/bin/env node
/**
 * `@navecss/eslint-plugin`'s style rule shares `@navecss/stylelint-config`'s property list and
 * allowlist without depending on that package (its manifest names neither that package nor
 * stylelint in any dependency field). This script is the link: it regenerates a plain-data copy
 * from the shipped config IN MEMORY (never a hand-copy) and diffs it, both ways, against the
 * committed recorded copy `packages/eslint-plugin/src/generated/style-properties.recorded.json`.
 * `--write` regenerates that file when the stylelint config's own property list changes on
 * purpose.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const RECORDED_PATH = path.join(
  ROOT,
  'packages/eslint-plugin/src/generated/style-properties.recorded.json',
)
const RULE_NAME = 'scale-unlimited/declaration-strict-value'

/**
 * Credit for the CSS Color 4 system colour keyword names that the generated copy carries inside
 * its `ignoreValues` patterns. `--write` puts it in the copy as `$credit`, which ships in the
 * plugin's tarball. Its wording is fixed: change it only together with
 * `packages/eslint-plugin/test/system-colors-credit.test.ts`, which pins it byte-exact.
 */
const SYSTEM_COLOR_CREDIT =
  'The ignoreValues patterns in this file contain the current <system-color> keywords, the names alone, copied from the System Colors section (https://www.w3.org/TR/css-color-4/#css-system-colors) of CSS Color Module Level 4 (W3C). Copyright (c) 2026 World Wide Web Consortium. That specification is published under the W3C Software and Document License (https://www.w3.org/copyright/software-license-2023/).'

/**
 * Regenerates the plain-data copy from `@navecss/stylelint-config`'s default export, read from
 * the workspace (a root devDependency; never a dependency of `eslint-plugin` itself).
 */
export async function extractStyleProperties() {
  const configUrl = pathToFileURL(path.join(ROOT, 'packages/stylelint-config/index.js')).href
  const { default: config } = await import(configUrl)
  const [properties, options] = config.rules[RULE_NAME]
  return {
    properties,
    ignoreValues: Object.fromEntries(
      properties.map((property) => [property, options.ignoreValues[property]]),
    ),
  }
}

/**
Renders `record`'s entries sorted by key, for a stable diff-friendly JSON file.
 */
export function sortedEntries(record) {
  return Object.fromEntries(Object.entries(record).toSorted(([a], [b]) => a.localeCompare(b)))
}

/**
Keys present on one side only, between two sets.
 */
function diffKeySets(recordedSet, emittedSet) {
  return {
    added: [...emittedSet].filter((key) => !recordedSet.has(key)),
    missing: [...recordedSet].filter((key) => !emittedSet.has(key)),
  }
}

/**
Symmetric added/missing/changed diff between the recorded and freshly emitted copies. `properties`
(the list the rule builds its entries from) and `ignoreValues`' keys are compared independently, so
a copy where one drifts from the shipped config without the other still fails.
 */
export function diffStyleProperties(recorded, emitted) {
  const properties = diffKeySets(new Set(recorded.properties), new Set(emitted.properties))
  const ignoreValueKeys = diffKeySets(
    new Set(Object.keys(recorded.ignoreValues)),
    new Set(Object.keys(emitted.ignoreValues)),
  )
  const added = [...new Set([...properties.added, ...ignoreValueKeys.added])]
  const missing = [...new Set([...properties.missing, ...ignoreValueKeys.missing])]
  const changed = Object.keys(emitted.ignoreValues)
    .filter((key) => Object.hasOwn(recorded.ignoreValues, key))
    .filter((key) => recorded.ignoreValues[key] !== emitted.ignoreValues[key])
  return { added, missing, changed }
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])

if (isMain) {
  const write = process.argv.includes('--write')
  const emitted = await extractStyleProperties()

  if (write) {
    writeFileSync(
      RECORDED_PATH,
      `${JSON.stringify(
        {
          $comment:
            "Generated by scripts/check-eslint-plugin-style-properties-drift.mjs --write from packages/stylelint-config's default export. Do not hand-edit.",
          $credit: SYSTEM_COLOR_CREDIT,
          properties: emitted.properties,
          ignoreValues: sortedEntries(emitted.ignoreValues),
        },
        undefined,
        2,
      )}\n`,
    )
    console.log('style-properties.recorded.json regenerated.')
  } else {
    const recorded = JSON.parse(readFileSync(RECORDED_PATH, 'utf8'))
    const result = diffStyleProperties(recorded, emitted)

    if (result.added.length > 0 || result.missing.length > 0 || result.changed.length > 0) {
      console.error(
        "@navecss/stylelint-config's property list disagrees with " +
          'packages/eslint-plugin/src/generated/style-properties.recorded.json:\n',
      )
      for (const key of result.added) {
        console.error(`  + ${key}  (in stylelint-config, missing from the recorded copy)`)
      }
      for (const key of result.missing) {
        console.error(`  - ${key}  (in the recorded copy, no longer in stylelint-config)`)
      }
      for (const key of result.changed) console.error(`  ~ ${key}  (ignoreValues changed)`)
      console.error(
        '\nIf this is intended, regenerate: node scripts/check-eslint-plugin-style-properties-drift.mjs --write',
      )
      process.exitCode = 1
    } else {
      console.log(
        `Style-properties copy: ${emitted.properties.length} entries, matches the recorded copy.`,
      )
    }
  }
}
